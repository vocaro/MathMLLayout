#!/usr/bin/env python3
"""Regenerate the issue #63 review packet from current Swift sources (macOS + Xcode)."""
import html
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "doc" / "speech-review"
LANGUAGES = {"en": "English", "fr": "French", "de": "German", "es": "Spanish", "it": "Italian"}


def generate():
    cases_path = Path(__file__).with_name("cases.json")
    cases = json.loads(cases_path.read_text())
    assert len({case["id"] for case in cases}) == len(cases)
    assert all(case["id"].isalnum() for case in cases)
    (OUTPUT / "images").mkdir(parents=True, exist_ok=True)
    sources = sorted((ROOT / "Sources" / "MathMLLayout").rglob("*.swift"))
    source_hash = hashlib.sha256()
    for source in sources:
        source_hash.update(str(source.relative_to(ROOT)).encode() + b"\0" + source.read_bytes())
    with tempfile.TemporaryDirectory(prefix="mathml-speech-review-") as directory:
        scratch = Path(directory)
        binary = scratch / "readings"
        subprocess.run(["xcrun", "swiftc", "-module-name", "MathMLLayout", "-module-cache-path",
                        str(scratch / "modules"), *map(str, sources),
                        str(Path(__file__).with_name("readings.swift")), "-o", str(binary)], check=True)
        subprocess.run([str(binary), str(cases_path), str(OUTPUT)], check=True)
    readings = json.loads((OUTPUT / "readings.json").read_text())
    revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    result = ["<!-- Generated by Tools/SpeechReview/generate.py; edit cases.json or introduction.md. -->\n",
              Path(__file__).with_name("introduction.md").read_text(),
              f"\n## Example snapshot\n\nReadings and images generated from the checkout at revision `{revision}`. "
              "They are actual implementation output, not proposed corrections or human approvals. "
              "No audio or voice validation is included.\n\n",
              f"Library-source SHA-256: `{source_hash.hexdigest()}`. This fingerprint includes any uncommitted "
              "Swift source changes present when generating the snapshot.\n\n",
              "The examples below retain the implementation's exact text, including punctuation, capitalization "
              "and literal author tokens. A formula image shows the current MathMLLayout rendering; "
              "it is context for the language review, not an independent rendering oracle.\n\n",
              "| Group | Cases | Review focus |\n| --- | --- | --- |\n"]
    groups = dict.fromkeys(case["group"] for case in cases)
    for group in groups:
        members = [case for case in cases if case["group"] == group]
        result.append(f"| [{group}](#{members[0]['anchor']}) | " + ", ".join(case["id"] for case in members) + " | " + members[0]["focus"] + " |\n")
    for group in groups:
        members = [case for case in cases if case["group"] == group]
        result.append(f"\n## {group}\n\n<a id=\"{members[0]['anchor']}\"></a>\n\n")
        for case in members:
            result.append(f"### {case['id']}: {case['title']}\n\n**Review:** {case['question']}\n\n")
            for language in case["languages"]:
                # HTML-escape author text so it cannot turn into Markdown/HTML markup.
                result.append(f"**{LANGUAGES[language]} (`{language}`)**\n\n> " + html.escape(readings[case["id"]][language], quote=False) + "\n\n")
            result.append("<details>\n<summary>Reveal intended structure, rendered context and MathML</summary>\n\n" + case["intent"] + "\n\n")
            if case["image"]:
                result.append(f"![{case['id']}: {case['alt']}](images/{case['id']}.png)\n\n")
            result.append("```xml\n" + case["markup"] + "\n```\n\n</details>\n\n")
    (OUTPUT / "README.md").write_text("".join(result).rstrip() + "\n")


if __name__ == "__main__":
    generate()
